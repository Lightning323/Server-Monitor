package org.pcMonitor;

import org.pcMonitor.applets.temprature.CPUTempMonitor;
import org.pcMonitor.applets.discord.bot.DiscordBot;
import org.pcMonitor.javalinWebapp.JavalinWebApp;
import org.pcMonitor.platform.Platform;
import org.pcMonitor.utils.Logging;

public class Main {

    /// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public static final String APP_VERSION = "8.9.0";
    public static boolean TEST_MODE = false;

    //2fa Key
    private static final String TEST_SECRET_KEY = "SLDK4NN5YPMV7SV5"; //Test secret key
    private static final String SECRET_KEY_2FA = TEST_SECRET_KEY;

    /// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


    public static DiscordBot bot;
    public static TaskbarTray taskbarTray;

    public static long minutesSinceAwake = 0;
    public static AppSettings settings = AppSettings.load();




    public static JavalinWebApp webApp = new JavalinWebApp();
    public static CPUTempMonitor tempMonitor = new CPUTempMonitor(Platform.SINGLETON, webApp);


    public static void main(String[] args) {
        System.out.println("Version: " + APP_VERSION);
        try {
            taskbarTray = new TaskbarTray();

            //Set the max frequency on startup
            if (settings.STARTUP_FREQUENCY_MHZ > 0) {
                System.out.println("Setting max frequency to " + Main.settings.STARTUP_FREQUENCY_MHZ);
                Platform.SINGLETON.setMaxFrequencyMHZ(Main.settings.STARTUP_FREQUENCY_MHZ);
            }

            //Start webapp
            webApp.start();

            //Start the bot
            try {
                if (Main.settings.DISCORD_BOT_TOKEN != null && !Main.settings.DISCORD_BOT_TOKEN.isEmpty()) {
                    bot = new DiscordBot(Main.settings.DISCORD_BOT_TOKEN);
                    bot.waitUntilReady();
                }
            } catch (Exception e) {
                e.printStackTrace();
            }

            //Start temp monitor
            tempMonitor.start();

            //Start taskbar tray
            taskbarTray.start();
        } catch (Exception e) {
            Logging.error(e);
        }
    }
}